"""Generates the check title list and the check catalogue from the engine.

Every check function in tasks.py starts with a docstring of the form
"AZURE-XXX-001 — Human readable title". From those this script writes:

- services/web-ui/src/checkTitles.json — titles for the dashboard, which only
  had hand-written titles for a few checks and showed the raw ID for the rest;
- docs/CHECKS.md — the check catalogue the README links to.

Run after adding or renaming a check:

    python scripts/gen_check_titles.py

`tests/test_checks.py` in the engine fails if either file is out of date.
Standard library only; does not import the engine.
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "services" / "assessment-engine" / "app" / "tasks.py"
OUT = ROOT / "services" / "web-ui" / "src" / "checkTitles.json"
CATALOGUE = ROOT / "docs" / "CHECKS.md"

# "ID — Title", or "ID / OLD-ID — Title" where a check was renumbered.
_DOC = re.compile(r"^(AZURE-[A-Z0-9-]+)(?:\s*/\s*AZURE-[A-Z0-9-]+)*\s+[—–-]\s+(.+)$")
_SEVERITY = re.compile(r'"severity"\s*:\s*"(Critical|High|Medium|Low)"')

# Same grouping as focus() in services/web-ui/src/App.tsx.
_DOMAINS = [
    ("Conditional Access", ("AZURE-CA-", "AZURE-RISK-")),
    ("MFA", ("AZURE-MFA-",)),
    ("Privileged Identity", ("AZURE-PIM-", "AZURE-PRIV-", "AZURE-BG-")),
    ("Applications", ("AZURE-APP-", "AZURE-CONSENT-")),
    ("Guests", ("AZURE-GUEST-",)),
    ("Groups", ("AZURE-GROUP-",)),
    ("Monitoring", ("AZURE-MONITORING-",)),
    ("Governance", ("AZURE-GOVERNANCE-",)),
]
_SEVERITY_ORDER = ["Critical", "High", "Medium", "Low"]


def collect_checks(source: str) -> dict:
    """{check_id: {"title": ..., "severity": ...}}, sorted by ID."""
    checks = {}
    for node in ast.parse(source).body:
        if not (isinstance(node, ast.FunctionDef) and node.name.startswith("check_")):
            continue
        first_line = (ast.get_docstring(node) or "").strip().splitlines()[:1]
        match = _DOC.match(first_line[0].strip()) if first_line else None
        if not match:
            continue
        severity = _SEVERITY.search(ast.get_source_segment(source, node) or "")
        checks[match.group(1)] = {
            "title": match.group(2).strip().rstrip("."),
            "severity": severity.group(1) if severity else "Medium",
        }
    return dict(sorted(checks.items()))


def collect_titles(source: str) -> dict:
    return {check_id: c["title"] for check_id, c in collect_checks(source).items()}


def render(titles: dict) -> str:
    return json.dumps(titles, indent=2, ensure_ascii=False) + "\n"


def domain_of(check_id: str) -> str:
    for name, prefixes in _DOMAINS:
        if check_id.startswith(prefixes):
            return name
    return "Identity"


def render_catalogue(checks: dict) -> str:
    by_domain = {}
    for check_id, c in checks.items():
        by_domain.setdefault(domain_of(check_id), []).append((check_id, c))
    counts = {s: sum(1 for c in checks.values() if c["severity"] == s) for s in _SEVERITY_ORDER}

    lines = [
        "# EntraGuard check catalogue",
        "",
        "<!-- Generated by scripts/gen_check_titles.py from the engine's check functions. Do not edit by hand. -->",
        "",
        f"EntraGuard runs **{len(checks)} checks** against a Microsoft Entra ID tenant: "
        + ", ".join(f"{counts[s]} {s}" for s in _SEVERITY_ORDER) + ".",
        "",
        "| Domain | Checks |",
        "|---|---|",
    ]
    for name in sorted(by_domain, key=lambda d: -len(by_domain[d])):
        lines.append(f"| [{name}](#{name.lower().replace(' ', '-')}) | {len(by_domain[name])} |")
    for name in sorted(by_domain, key=lambda d: -len(by_domain[d])):
        lines += ["", f"## {name}", "", "| Check ID | Severity | What it checks |", "|---|---|---|"]
        rows = sorted(by_domain[name], key=lambda r: (_SEVERITY_ORDER.index(r[1]["severity"]), r[0]))
        lines += [f"| `{check_id}` | {c['severity']} | {c['title']} |" for check_id, c in rows]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    checks = collect_checks(TASKS.read_text(encoding="utf-8"))
    OUT.write_text(render(collect_titles(TASKS.read_text(encoding="utf-8"))), encoding="utf-8", newline="\n")
    CATALOGUE.write_text(render_catalogue(checks), encoding="utf-8", newline="\n")
    print(f"wrote {len(checks)} checks to {OUT.relative_to(ROOT)} and {CATALOGUE.relative_to(ROOT)}")
